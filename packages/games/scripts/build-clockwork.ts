/**
 * Writes `src/clockwork-offsets.ts`: each Clockwork zone's UTC offset on each of
 * the game's fixed dates, from the IANA time zone database that ships with Node
 * (`process.versions.tz`). The game reads only this table, never the runtime's
 * own time zone data, so a player's browser and the server always agree.
 *
 * Run: node packages/games/scripts/build-clockwork.ts
 */
import { writeFileSync } from 'node:fs';
import { CLOCK_DATES } from '../src/clockwork-dates.ts';
import { CLOCK_PLACES } from '../src/clockwork-places.ts';

/** The zone's offset from UTC, in minutes, at an instant. */
function offsetAt(zone: string, instant: Date): number {
  const name = new Intl.DateTimeFormat('en', { timeZone: zone, timeZoneName: 'longOffset' })
    .formatToParts(instant)
    .find((p) => p.type === 'timeZoneName')!.value;
  const m = /GMT(?:([+-])(\d\d):(\d\d))?/.exec(name);
  if (!m) throw new Error(`can't read offset ${name} for ${zone}`);
  return m[1] ? (m[1] === '-' ? -1 : 1) * (Number(m[2]) * 60 + Number(m[3])) : 0;
}

const zones = [...new Set(CLOCK_PLACES.map((p) => p.zone))].sort();
const rows = zones.map((zone) => {
  const offsets = CLOCK_DATES.map(({ month, day }) => {
    // The whole UTC day, and either side of it, so no clock change falls on a level's date.
    const hours = [-12, 0, 12, 23, 36].map((h) => offsetAt(zone, new Date(Date.UTC(2026, month - 1, day, h))));
    if (new Set(hours).size !== 1) throw new Error(`${zone} changes its clock near ${day}/${month}`);
    return hours[0]!;
  });
  return `  '${zone}': [${offsets.join(', ')}],`;
});

writeFileSync(
  new URL('../src/clockwork-offsets.ts', import.meta.url),
  `// Generated by scripts/build-clockwork.ts from the IANA time zone database. Don't edit by hand.

/** The tzdb release the offsets come from. */
export const CLOCK_TZDB = '${process.versions.tz}';

/** Each zone's UTC offset in minutes on each of CLOCK_DATES, in 2026. */
export const CLOCK_OFFSETS: Readonly<Record<string, readonly number[]>> = {
${rows.join('\n')}
};
`,
);
console.log(`${zones.length} zones from tzdb ${process.versions.tz}`);
